export type IconName = keyof typeof ICONS

/** иконка в тексте сообщения */
export function icon(name: IconName): Formatted {
  const [id, fallback] = ICONS[name]
  return customEmoji(fallback, id)
}

/** иконка перед текстом инлайн-кнопки; эмодзи в самом тексте кнопки тогда не нужен */
export function withIcon(button: TelegramInlineKeyboardButton, name: IconName): TelegramInlineKeyboardButton {
  return { ...button, icon_custom_emoji_id: ICONS[name][0] }
}
